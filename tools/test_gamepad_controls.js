'use strict';
const assert = require('node:assert/strict');
const G = require('../gamepad-controls.js');
const defaults = G.createDefaultProfile();
const pad = axes => ({ axes, buttons: [] });
assert.equal(G.readAxis(pad([0, 0, 0, 0]), defaults, 'roll'), 0);
assert.equal(G.readAxis(pad([0, 0, 0, -1]), defaults, 'throttle'), 1, 'default throttle inversion preserves common -1 idle convention');
assert.equal(G.readThrottle(pad([0, 0, 0, -1]), defaults), 1);
assert.equal(G.readThrottle(pad([0, 0, 0, 1]), defaults), 0);
let p = G.normalizeProfile({ deadzone: 0.1, axes: { roll: 0 }, invert: { roll: false } });
assert.equal(G.readAxis(pad([0.1]), p, 'roll'), 0, 'dead zone suppresses center noise');
assert.ok(Math.abs(G.readAxis(pad([0.55]), p, 'roll') - 0.5) < 1e-9, 'dead zone rescales the remaining travel');
p = G.normalizeProfile({ deadzone: 0, sensitivity: 2, axes: { roll: 0 }, invert: { roll: false } });
assert.ok(Math.abs(G.readAxis(pad([0.25]), p, 'roll') - 0.5) < 1e-9, 'sensitivity curve changes response');
p = G.normalizeProfile({ deadzone: 0, centers: { roll: 0.2 }, axes: { roll: 0 }, invert: { roll: false } });
assert.equal(G.readAxis(pad([0.2]), p, 'roll'), 0, 'center calibration removes neutral offset');
p = G.normalizeProfile({ deadzone: 0, throttleMode: 'unipolar', axes: { throttle: 0 }, invert: { throttle: false } });
assert.equal(G.readThrottle(pad([0]), p), 0);
assert.equal(G.readThrottle(pad([1]), p), 1);
p = G.normalizeProfile({ deadzone: 0, brakeMode: 'unipolar', axes: { brake: 0 }, invert: { brake: false } });
assert.equal(G.readBrake(pad([0.8]), p), 0.8);
p = G.normalizeProfile({ axes: { roll: -1, throttle: -1, brake: -1 } });
assert.equal(G.readAxis(pad([1]), p, 'roll'), 0, 'disabled axes return neutral');
console.log('PASS gamepad controls: axis selection, dead zone, sensitivity, center calibration, inversion, throttle/brake ranges');